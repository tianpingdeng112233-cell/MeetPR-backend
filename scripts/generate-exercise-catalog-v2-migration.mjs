#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');

const defaultCatalogPath = path.resolve(
  repoRoot,
  '../MeetPR-feat025-auth/Modules/CoachKit/Sources/CoachKit/Resources/exercise-catalog-v2.json',
);
const defaultOutputPath = path.resolve(
  repoRoot,
  'db/migrations/0002.1-align-exercises-catalog-v2.sql',
);

const catalogPath = path.resolve(process.argv[2] ?? defaultCatalogPath);
const outputPath = path.resolve(process.argv[3] ?? defaultOutputPath);

const MOVEMENT_PATTERNS = [
  'squat',
  'hip_hinge',
  'horizontal_push',
  'vertical_push',
  'horizontal_pull',
  'vertical_pull',
  'warm_up',
  'other',
];

const REQUIRED_KEYS = [
  'id',
  'name',
  'exerciseType',
  'mainLiftFamily',
  'isCompetitionLift',
  'muscleGroups',
  'equipment',
  'movementPattern',
  'nameEn',
];

function readCatalog(inputPath) {
  const catalog = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
  if (!Array.isArray(catalog)) {
    throw new TypeError('exercise catalog must be a JSON array');
  }
  return catalog;
}

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function textArray(values) {
  return `ARRAY[${values.map(sqlString).join(', ')}]::TEXT[]`;
}

function collectDistinct(catalog, key) {
  return [...new Set(catalog.flatMap((exercise) => exercise[key] ?? []))].sort();
}

function validateCatalog(catalog) {
  const ids = new Set();
  for (const [index, exercise] of catalog.entries()) {
    for (const key of REQUIRED_KEYS) {
      if (!(key in exercise)) {
        throw new Error(`exercise at index ${index} is missing ${key}`);
      }
    }
    if (ids.has(exercise.id)) {
      throw new Error(`duplicate exercise id: ${exercise.id}`);
    }
    ids.add(exercise.id);
    if (!['accessory', 'main_lift_variation'].includes(exercise.exerciseType)) {
      throw new Error(`unsupported exerciseType for ${exercise.id}: ${exercise.exerciseType}`);
    }
    if (!Array.isArray(exercise.muscleGroups) || exercise.muscleGroups.length === 0) {
      throw new Error(`exercise ${exercise.id} must have at least one muscle group`);
    }
    if (!Array.isArray(exercise.equipment) || exercise.equipment.length === 0) {
      throw new Error(`exercise ${exercise.id} must have at least one equipment value`);
    }
    if (!Array.isArray(exercise.movementPattern)) {
      throw new Error(`exercise ${exercise.id} movementPattern must be an array`);
    }
    for (const pattern of exercise.movementPattern) {
      if (!MOVEMENT_PATTERNS.includes(pattern)) {
        throw new Error(`unsupported movementPattern for ${exercise.id}: ${pattern}`);
      }
    }
  }
}

function buildMigration(catalog) {
  validateCatalog(catalog);

  const muscleGroups = collectDistinct(catalog, 'muscleGroups');
  const equipment = collectDistinct(catalog, 'equipment');
  const rows = catalog
    .map((exercise) => {
      return `  (${[
        `${sqlString(exercise.id)}::UUID`,
        sqlString(exercise.name),
        sqlString(exercise.nameEn),
        sqlString(exercise.exerciseType),
        sqlString(exercise.mainLiftFamily),
        exercise.isCompetitionLift ? 'TRUE' : 'FALSE',
        textArray(exercise.muscleGroups),
        textArray(exercise.equipment),
        textArray(exercise.movementPattern),
      ].join(', ')})`;
    })
    .join(',\n');

  return `-- Migration 0002.1: align exercises with iOS exercise-catalog-v2.
-- Spec: specs/002-coach-planning-crud/SPEC.md
-- Source: ${path.relative(repoRoot, catalogPath)}
-- Generated by: scripts/generate-exercise-catalog-v2-migration.mjs

BEGIN;

ALTER TABLE exercises
  ADD COLUMN name_en TEXT CHECK (name_en IS NULL OR length(name_en) BETWEEN 1 AND 120);

ALTER TABLE exercises
  DROP CONSTRAINT exercises_muscle_groups_valid,
  DROP CONSTRAINT exercises_equipment_valid,
  DROP CONSTRAINT exercises_movement_pattern_valid;

DELETE FROM exercises
WHERE created_by_coach_id IS NULL
  AND NOT (
    exercise_type = 'main_lift'
    AND is_competition_lift = TRUE
    AND main_lift_family IN ('squat', 'bench', 'deadlift')
  );

UPDATE exercises
SET
  name_en = CASE main_lift_family
    WHEN 'squat' THEN 'Competition Squat'
    WHEN 'bench' THEN 'Competition Bench Press'
    WHEN 'deadlift' THEN 'Competition Deadlift'
    ELSE name_en
  END,
  movement_pattern = CASE main_lift_family
    WHEN 'squat' THEN ARRAY['squat']::TEXT[]
    WHEN 'bench' THEN ARRAY['horizontal_push']::TEXT[]
    WHEN 'deadlift' THEN ARRAY['hip_hinge']::TEXT[]
    ELSE movement_pattern
  END
WHERE created_by_coach_id IS NULL
  AND exercise_type = 'main_lift'
  AND is_competition_lift = TRUE
  AND main_lift_family IN ('squat', 'bench', 'deadlift');

UPDATE exercises
SET movement_pattern = array_replace(
  array_replace(movement_pattern, 'push', 'horizontal_push'),
  'pull',
  'horizontal_pull'
)
WHERE movement_pattern && ARRAY['push', 'pull']::TEXT[];

ALTER TABLE exercises
  ADD CONSTRAINT exercises_muscle_groups_valid CHECK (
    muscle_groups <@ ${textArray(muscleGroups)}
    AND cardinality(muscle_groups) >= 1
  ),
  ADD CONSTRAINT exercises_equipment_valid CHECK (
    equipment <@ ${textArray(equipment)}
    AND cardinality(equipment) >= 1
  ),
  ADD CONSTRAINT exercises_movement_pattern_valid CHECK (
    movement_pattern <@ ${textArray(MOVEMENT_PATTERNS)}
  );

INSERT INTO exercises (
  id,
  name,
  name_en,
  exercise_type,
  main_lift_family,
  is_competition_lift,
  muscle_groups,
  equipment,
  movement_pattern
) VALUES
${rows}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  name_en = EXCLUDED.name_en,
  exercise_type = EXCLUDED.exercise_type,
  main_lift_family = EXCLUDED.main_lift_family,
  is_competition_lift = EXCLUDED.is_competition_lift,
  muscle_groups = EXCLUDED.muscle_groups,
  equipment = EXCLUDED.equipment,
  movement_pattern = EXCLUDED.movement_pattern,
  created_by_coach_id = NULL;

COMMIT;
`;
}

const catalog = readCatalog(catalogPath);
const sql = buildMigration(catalog);

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, sql);
console.log(`Wrote ${catalog.length} exercises to ${path.relative(repoRoot, outputPath)}`);
console.log(`muscle_groups: ${collectDistinct(catalog, 'muscleGroups').join(', ')}`);
console.log(`equipment: ${collectDistinct(catalog, 'equipment').join(', ')}`);
console.log(`movement_pattern: ${MOVEMENT_PATTERNS.join(', ')}`);
